package nl.serviceplanet.closuretemplates.toolbox.maven;

import nl.serviceplanet.closuretemplates.toolbox.util.SoyTestUtil;
import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.Test;

import java.nio.file.Path;
import java.util.List;

/**
 * Verifies the {@code --togglesFiles} and {@code --generated_files} flags the Maven goals hand to the Soy compiler.
 * The contract is: Every source and toggles file is passed as an absolute path (so it resolves independently of the
 * working directory of the process), with a {@code --generated_files} entry mapping it back to its workdir-relative
 * logical path (so template names and toggle import paths stay stable).
 */
public final class TogglesCliFlagsTest {

	/** Concrete stand-in, since the flags are generated by the abstract base class shared by all goals. */
	private static final class TestMojo extends AbstractClosureTemplatesCompilerMojo {
		@Override
		public void execute() {
		}
	}

	private static final Path CWD = Path.of("").toAbsolutePath();

	private static final String TOGGLES_LOGICAL_PATH =
			"src/test/resources/" + SoyTestUtil.getDirectoryOfUnitTestResources() + "/feature.toggles";

	private static List<String> flagsFor(String togglesFiles, String togglesFilesBasePath) {
		TestMojo mojo = new TestMojo();
		mojo.togglesFiles = togglesFiles;
		mojo.togglesFilesBasePath = togglesFilesBasePath;
		return mojo.generateBaseCliFlags();
	}

	private static String flagValue(List<String> flags, String flag) {
		int flagIndex = flags.indexOf(flag);
		Assertions.assertTrue(flagIndex >= 0, () -> "no " + flag + " flag in " + flags);
		return flags.get(flagIndex + 1);
	}

	@Test
	public void testNoTogglesOmitsTheFlagsEntirely() {
		List<String> flags = flagsFor(null, null);

		Assertions.assertFalse(flags.contains("--togglesFiles"));
		Assertions.assertFalse(flags.contains("--generated_files"));
	}

	@Test
	public void testExplicitTogglesFilesAreAbsolutizedAndMappedToTheirRelativeSpelling() {
		List<String> flags = flagsFor("a/my.toggles,b/other.toggles", null);

		// The compiler reads the files through the absolute paths...
		Assertions.assertEquals(
				CWD.resolve("a/my.toggles") + "," + CWD.resolve("b/other.toggles"),
				flagValue(flags, "--togglesFiles"));

		// ...but knows them by the relative paths the templates import them by.
		Assertions.assertEquals(
				CWD.resolve("a/my.toggles") + "=a/my.toggles," + CWD.resolve("b/other.toggles") + "=b/other.toggles",
				flagValue(flags, "--generated_files"));
	}

	@Test
	public void testTogglesFilesBasePathIsScannedRecursively() {
		// The test resources hold exactly one toggles file.
		List<String> flags = flagsFor(null, "src/test/resources");

		Assertions.assertEquals(
				CWD.resolve(TOGGLES_LOGICAL_PATH).toString(),
				flagValue(flags, "--togglesFiles"));
		Assertions.assertEquals(
				CWD.resolve(TOGGLES_LOGICAL_PATH) + "=" + TOGGLES_LOGICAL_PATH,
				flagValue(flags, "--generated_files"));
	}

	/**
	 * The Soy compiler matches a toggle import against the logical path as an exact string, so a base path of './'
	 * must not leak a './' prefix into the logical paths.
	 */
	@Test
	public void testLogicalPathsAreNormalized() {
		List<String> flags = flagsFor(null, "./src/test/resources");

		Assertions.assertEquals(
				CWD.resolve(TOGGLES_LOGICAL_PATH) + "=" + TOGGLES_LOGICAL_PATH,
				flagValue(flags, "--generated_files"));
	}

	@Test
	public void testBasePathAndExplicitFilesAreCombined() {
		List<String> flags = flagsFor("extra/my.toggles", "src/test/resources");

		Assertions.assertEquals(
				CWD.resolve(TOGGLES_LOGICAL_PATH) + "," + CWD.resolve("extra/my.toggles"),
				flagValue(flags, "--togglesFiles"));
	}

	/**
	 * An absolute path is passed through untouched and keeps an absolute logical path, so it gets no
	 * {@code --generated_files} entry.
	 */
	@Test
	public void testAbsoluteTogglesFileIsPassedThrough() {
		String absolute = CWD.resolve("somewhere/my.toggles").toString();
		List<String> flags = flagsFor(absolute, null);

		Assertions.assertEquals(absolute, flagValue(flags, "--togglesFiles"));
		Assertions.assertFalse(flags.contains("--generated_files"));
	}
}
